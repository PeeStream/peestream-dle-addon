                if (isset($this->posts[$pid]) &&
                    $this->posts[$pid]['xfields'] === $exp_xf &&
                    $this->posts[$pid]['short_story'] === $exp_short &&
                    $this->posts[$pid]['full_story'] === $exp_full) {
                    // Update state
                    preg_match("/SET xfields='(.*?)', short_story='(.*?)', full_story='(.*?)'/s", $q_str, $set_m);
